def get_all_targets():
    return TARGET_REGISTRY


def get_targets_by_difficulty(difficulty):
    return [
        target
        for target in TARGET_REGISTRY
        if target["difficulty"] == difficulty
    ]


def get_target_by_name(name):
    for target in TARGET_REGISTRY:
        if target["name"] == name:
            return target

    raise ValueError(f"Unknown target: {name}")


def get_target_names():
    return [target["name"] for target in TARGET_REGISTRY]